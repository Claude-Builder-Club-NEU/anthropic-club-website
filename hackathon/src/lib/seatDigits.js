/**
 * The Seats figure's digits, as bitmaps.
 *
 * WHY NOT THE FILTER. The figure used to be ordinary Funnel Display text run
 * through an SVG pixelate filter (feFlood, feTile, feMorphology). That filter
 * renders nothing at all in some browsers — on a phone the number simply was
 * not there — and a figure that vanishes is worse than one that is not
 * pixelated. So the pixelation is done once, here, and the page draws blocks.
 * Nothing about it depends on a filter, a canvas or a font loading.
 *
 * WHERE THESE CAME FROM. Funnel Display 800, the face the figure was set in,
 * rasterised on a canvas and sampled one cell at a time: a cell is lit when
 * the glyph covers at least half of it. The cap top sits on a row boundary,
 * and every digit shares one box (the digits are tabular, 0.575em each), so
 * any two of them line up. Regenerate the same way if the face ever changes.
 *
 * TWO DENSITIES, so the blocks stay about the 6px they were under the filter
 * as the figure scales from 150px to 420px: `coarse` is 25 cells to the em
 * and is used up to 1024px wide, `fine` is 48 to the em and is used above.
 * The CSS picks one; both are in the markup.
 *
 * Each glyph is `rows` strings of `cols` characters; `#` is a lit cell.
 */
